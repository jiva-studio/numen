	src := "package p\n\n// A.\n// B.\n// C.\n// D.\n// E.\n// F.\n//\n//numen:api\ntype T struct {\n\t// Name is shown.\n\t// Second line.\n\t// Third line.\n\t// Fourth line.\n\t// Fifth line.\n\t// Sixth line.\n\tName string\n}\n"
