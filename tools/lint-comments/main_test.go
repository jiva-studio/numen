package main

import (
	"strings"
	"testing"
)

func TestCheckReportsFieldComments(t *testing.T) {
	src := "package p\n\ntype T struct {\n\t// Name is the name.\n\tName string\n\tsize int // in bytes\n\tplain bool\n}\n"
	findings, fixed, err := Check("libs/core/p/p.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 2 || findings[0].Line != 4 || findings[1].Line != 6 {
		t.Fatalf("findings = %+v, want lines 4 and 6", findings)
	}
	want := "package p\n\ntype T struct {\n\tName  string\n\tsize  int\n\tplain bool\n}\n"
	if string(fixed) != want {
		t.Fatalf("fixed =\n%s\nwant\n%s", fixed, want)
	}
}

func TestCheckReportsUnexportedFunctionDocs(t *testing.T) {
	src := "package p\n\n// Open opens.\nfunc Open() {}\n\n// read reads.\n//\n//go:noinline\nfunc read() {}\n"
	findings, fixed, err := Check("p.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 1 || !strings.Contains(findings[0].Message, "function read") {
		t.Fatalf("findings = %+v, want one on read", findings)
	}
	if !strings.Contains(string(fixed), "// Open opens.") || !strings.Contains(string(fixed), "//go:noinline\nfunc read") || strings.Contains(string(fixed), "read reads") {
		t.Fatalf("fixed =\n%s", fixed)
	}
}

func TestCheckKeepsExportedFieldCommentsOfAMarkedType(t *testing.T) {
	for _, marker := range []string{"//numen:settings", "//numen:api"} {
		src := "package p\n\n// Spec describes a tool.\n//\n" + marker + "\ntype Spec struct {\n\t// Name is shown to the user.\n\tName string\n\t// cache is filled on first use.\n\tcache map[string]int\n}\n\n// Other is not marked.\ntype Other struct {\n\t// Name is the name.\n\tName string\n}\n"
		findings, fixed, err := Check("p.go", []byte(src))
		if err != nil {
			t.Fatal(err)
		}
		if len(findings) != 2 || findings[0].Line != 9 || findings[1].Line != 15 {
			t.Fatalf("%s: findings = %+v, want the unexported field on line 9 and the unmarked type on line 15", marker, findings)
		}
		if !strings.Contains(string(fixed), marker+"\ntype Spec") || !strings.Contains(string(fixed), "Name is shown to the user") {
			t.Fatalf("%s: fixed =\n%s", marker, fixed)
		}
	}
}

func TestCheckKeepsDirectives(t *testing.T) {
	src := "package p\n\ntype T struct {\n\t// gomutants:disable-next-line BRANCH_IF reason=\"x\"\n\tA int\n}\n\n//go:noinline\nfunc f() {}\n"
	findings, _, err := Check("p.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Fatalf("findings = %+v, want none", findings)
	}
}

func TestCheckSkipsGeneratedFiles(t *testing.T) {
	src := "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n\ntype T struct {\n\t// A is a.\n\tA int\n}\n"
	findings, _, err := Check("p.pb.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Fatalf("findings = %+v, want none", findings)
	}
}
