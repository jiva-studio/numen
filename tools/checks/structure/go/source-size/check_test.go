// Package sourcesize is the check `go/source-size`, run on the tree with the planted violations that prove it.
package sourcesize

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/jiva-studio/numen/tools/checks/structure/go/load"
)

func getTreeLimits() sizeLimits {
	return sizeLimits{file: maxFileLines, pkg: maxPackageLines, width: maxLineWidth}
}

func TestNoSourceFileOrPackageIsLarge(t *testing.T) {
	root, err := filepath.Abs(load.RepoRootDir)
	if err != nil {
		t.Fatal(err)
	}
	trees, err := listModuleTrees(root)
	if err != nil {
		t.Fatal(err)
	}
	found, files, dirs, err := getOversizedSources(root, trees, getTreeLimits())
	if err != nil {
		t.Fatal(err)
	}
	for _, one := range found {
		t.Error(one)
	}
	if len(trees) < 20 || files == 0 || dirs == 0 {
		t.Fatalf("%d files in %d directories of %d modules read: the rule is checked against nothing", files, dirs, len(trees))
	}
}

func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, text := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func code(n int) string { return "package p\n" + strings.Repeat("var _ = 1\n", n-1) }

// The rule counts the lines of code of a production file, not its blank and comment lines, reads no test
// file for size, and sums a directory without its subdirectories or nested modules.
func TestSourceSizeRule_CountsLinesOfCodePerFileAndDirectory(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"m/go.mod":         "module m\n",
		"m/a/long.go":      code(10),
		"m/a/short.go":     code(3),
		"m/a/padded.go":    "package p\n\n// a comment\n/* block\ncomment */\n" + strings.Repeat("\n// text\n", 20) + "var _ = 1\n",
		"m/a/long_test.go": code(50),
		"m/a/sub/other.go": code(4),
		"m/n/go.mod":       "module n\n",
		"m/n/nested.go":    code(30),
	})
	found, files, dirs, err := getOversizedSources(dir, []string{"m"}, sizeLimits{file: 8, pkg: 12, width: 200})
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"m/a has 15 lines of code in all, more than 12", "m/a/long.go has 10 lines of code, more than 8"}
	if !slices.Equal(found, want) {
		t.Errorf("the rule rejects %v, want %v", found, want)
	}
	if files != 4 || dirs != 2 {
		t.Errorf("%d files and %d directories read, want 4 and 2", files, dirs)
	}
}

// A raw string literal counts every line it spans, so a file cannot hide its lines in one.
func TestSourceSizeRule_CountsEveryLineOfARawString(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"m/go.mod": "module m\n",
		"m/a.go":   "package p\n\nvar _ = `\none\n\ntwo\n`\n",
	})
	found, _, _, err := getOversizedSources(dir, []string{"m"}, sizeLimits{file: 5, pkg: 100, width: 200})
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"m/a.go has 6 lines of code, more than 5"}; !slices.Equal(found, want) {
		t.Errorf("the rule rejects %v, want %v", found, want)
	}
}

// A line wider than the limit is refused in a production file and in a test file, and a generated file is
// not read.
func TestSourceSizeRule_RejectsAWideLineOfAHandWrittenFile(t *testing.T) {
	wide := "var _ = \"" + strings.Repeat("x", 200) + "\"\n"
	dir := writeTree(t, map[string]string{
		"m/go.mod":       "module m\n",
		"m/buf.gen.yaml": "plugins:\n  - local: protoc-gen-go\n    out: gen\n",
		"m/a.go":         "package p\n\n" + wide,
		"m/a_test.go":    "package p\n\nvar _ = 1\n" + wide,
		"m/gen/g.pb.go":  "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n\n" + wide,
	})
	found, _, _, err := getOversizedSources(dir, []string{"m"}, getTreeLimits())
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"m/a.go:3 is wider than 200 characters", "m/a_test.go:4 is wider than 200 characters"}
	if !slices.Equal(found, want) {
		t.Errorf("the rule rejects %v, want %v", found, want)
	}
}

// A file that carries the generated header without a generator that writes it is hand-written: the header
// does not exempt it from the limits.
func TestSourceSizeRule_RejectsAGeneratedHeaderNoGeneratorProduces(t *testing.T) {
	header := "// Code generated by m/tools/make.mjs. DO NOT EDIT.\n\n"
	dir := writeTree(t, map[string]string{
		"go.work":                 "go 1.26\n\nuse (\n\t./m\n\t./m/sub\n)\n",
		"m/go.mod":                "module m\n",
		"m/tools/make.mjs":        "write('../out/made.go', text)\n",
		"m/out/made.go":           header + code(30),
		"m/out/forged.go":         header + code(30),
		"m/buf.gen.yaml":          "plugins:\n  - local: protoc-gen-go\n    out: gen\n    opt: paths=source_relative\n",
		"m/gen/v1/x.pb.go":        "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n" + code(30),
		"m/elsewhere/y.pb.go":     "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n" + code(30),
		"m/sub/go.mod":            "module sub\n",
		"m/sub/handwritten.go":    "package p\n",
		"m/a_gen.go":              "// Code generated by hand. DO NOT EDIT.\n\npackage p\n",
		"m/tools/other_script.go": "package main\n",
	})
	trees, err := listModuleTrees(dir)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"m", "m/sub"}; !slices.Equal(trees, want) {
		t.Fatalf("the modules of go.work are %v, want %v", trees, want)
	}
	found, _, _, err := getOversizedSources(dir, trees, sizeLimits{file: 100, pkg: 200, width: 200})
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"m/a_gen.go:1 claims `// Code generated by hand. DO NOT EDIT.`, and no generator produces the file",
		"m/elsewhere/y.pb.go:1 claims `// Code generated by protoc-gen-go. DO NOT EDIT.`, and no generator produces the file",
		"m/out/forged.go:1 claims `// Code generated by m/tools/make.mjs. DO NOT EDIT.`, and no generator produces the file",
	}
	if !slices.Equal(found, want) {
		t.Errorf("the rule rejects %v, want %v", found, want)
	}
}

