// A function only a test calls, a test-support function no test uses with what only it calls (a
// generic one too), an unused method and an unexported function no root reaches are reported. A
// function called from a file of another platform, the exports of a bound package, the functions that a
// test selects from test support (a *test package, a testsupport package or one under
// internal/testsupport) with what they call, the methods of the types of test support that a test
// imports or that such test support imports, such as a method a test calls on the value of a
// constructor or of a field, what the body of a selected generic function calls, a generated function
// and a marker method are not.
func TestDeadcodeRule_FindsThePlantedFunctions(t *testing.T) {
	dir := load.WriteTreeFixture(t, listPlantedFiles())
	s := scope{root: getRealDir(t, dir), patterns: []string{"./libs/...", "./plugins/...", "./apps/..."}, env: []string{"GOWORK=off"}}
	var got []string
	for _, one := range findUnreachableFunctions(t, s) {
		got = append(got, one.Name)
	}
	slices.Sort(got)
	want := []string{
		"fixture/apps/mobile/bind.stop",
		"fixture/libs/notes.(Note).Unused",
		"fixture/libs/notes.Hidden",
		"fixture/libs/notes.OnlyTested",
		"fixture/libs/notes.Total",
		"fixture/libs/notes/internal/testsupport/notesfake.Spare",
		"fixture/libs/notes/notestest.Idle",
		"fixture/libs/notes/notestest.Unused",
	}
	if !slices.Equal(got, want) {
		t.Errorf("findings\n%v\nwant\n%v", got, want)
	}
}

// The kept list names a function, every method of a type, or every function of a package, and nothing
// next to them.
func TestIsException_MatchesOnlyTheListedNames(t *testing.T) {
	const catalog = "github.com/jiva-studio/numen/libs/plugin/catalog/"
	for _, name := range []string{
		catalog + "catalog.NewCachedSource",
		catalog + "catalog.(*CachedSource).List",
		catalog + "snapshotcache.(*Cache).Read",
		catalog + "packagecache.New",
	} {
		if !isException(name) {
			t.Errorf("%s is not kept", name)
		}
	}
	for _, name := range []string{
		catalog + "catalog.NewCachedSourceFor",
		catalog + "catalog.(*Service).List",
		catalog + "catalogtest.(*FakeSource).List",
		catalog + "packagecachex.New",
	} {
		if isException(name) {
			t.Errorf("%s is kept", name)
		}
	}
}

