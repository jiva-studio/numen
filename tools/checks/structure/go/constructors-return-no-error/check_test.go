// Package constructorsreturnnoerror is the check `go/constructors-return-no-error`, run on the tree with the planted violations that prove it.
package constructorsreturnnoerror

import (
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/jiva-studio/numen/tools/checks/structure/go/load"
)

// A constructor of the use cases and of the adapters takes its collaborators and returns the value: it
// validates nothing and answers with no error.
func TestNoConstructorOfAUseCaseOrAnAdapterReturnsAnError(t *testing.T) {
	findings, files := getFallibleConstructors(t, filepath.Join("..", "usecase"), filepath.Join("..", "adapter"))
	if files == 0 {
		t.Fatal("no Go file was read under usecase and adapter")
	}
	for _, one := range findings {
		t.Error(one + ": a constructor returns the value and no error")
	}
}

func TestConstructorRule_RejectsAConstructorThatAnswersWithAnError(t *testing.T) {
	root := t.TempDir()
	write := func(name, text string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(filepath.Join(root, name)), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, name), []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("find/find.go", `package find

import "errors"

type Find struct{}

func NewFind(readers any) (*Find, error) {
	if readers == nil {
		return nil, errors.New("find needs readers")
	}
	return &Find{}, nil
}

func NewOnly(
	readers any,
) (found *Find, failed error) {
	return &Find{}, nil
}

func NewPlain(readers any) *Find { return &Find{} }

func NewBuilt() (*Find, bool) { return &Find{}, true }

func Open() (*Find, error) { return &Find{}, nil }

func (Find) NewMethod() error { return nil }
`)
	write("find/find_test.go", "package find\n\nfunc NewForTest() error { return nil }\n")
	write("find/generated.go", "// Code generated by a tool. DO NOT EDIT.\n\npackage find\n\nfunc NewGenerated() error { return nil }\n")

	findings, files := getFallibleConstructors(t, root)

	rel := func(name string) string { return filepath.Join(root, "find", name) }
	want := []string{rel("find.go:7"), rel("find.go:14")}
	slices.Sort(findings)
	if !slices.Equal(findings, want) {
		t.Errorf("the rule rejects %v, want %v", findings, want)
	}
	if files != 1 {
		t.Errorf("%d files read, want 1", files)
	}
}

