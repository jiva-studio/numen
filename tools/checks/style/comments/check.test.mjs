import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { findScriptComments, removeRanges } from './check.mjs'

const lines = (file, text) => findScriptComments(file, text).map((finding) => finding.line)

describe('properties', () => {
  it('rejects a comment on an interface, type or class property', () => {
    const text = [
      'interface A {',
      '  /** The id. */',
      '  id: string',
      '  size: number // in bytes',
      '}',
      'type B = {',
      '  // The name.',
      '  name: string',
      '}',
      'class C {',
      '  /** The count. */',
      '  count = 0',
      '}',
    ].join('\n')
    assert.deepEqual(lines('libs/core/client/src/a.ts', text), [2, 4, 7, 11])
  })

  it('rejects a comment on a prop of a Vue component', () => {
    const text = [
      '<script setup lang="ts">',
      'defineProps<{',
      '  /** What did not load. */',
      '  message: string',
      '}>()',
      '</script>',
      '<template><p /></template>',
    ].join('\n')
    assert.deepEqual(lines('apps/desktop/editor/src/A.vue', text), [3])
  })

  it('keeps directives and @deprecated', () => {
    const text = [
      'interface A {',
      '  // @ts-expect-error the field is set by the host',
      '  a: string',
      '  // Stryker disable next-line StringLiteral: the empty name is never compared',
      '  b: string',
      '  /** @deprecated use c */',
      '  d: string',
      '}',
    ].join('\n')
    assert.deepEqual(lines('a.ts', text), [])
  })
})

describe('functions', () => {
  it('rejects a doc comment on an unexported function and keeps it on an exported one', () => {
    const text = [
      '/** Opens a file. */',
      'export function open() {}',
      '',
      '/** Reads a file. */',
      'function read() {}',
      '',
      '/** Writes a file. */',
      'const write = () => {}',
      '',
      'class D {',
      '  /** Closes. */',
      '  private close() {}',
      '  /** Flushes. */',
      '  flush() {}',
      '}',
    ].join('\n')
    assert.deepEqual(lines('a.ts', text), [4, 7, 11])
  })

  it('keeps a file header and a section banner above a function', () => {
    const text = [
      '/** The tab model. */',
      '',
      '/* -------------------------------- Handlers -------------------------------- */',
      'function onClose() {}',
    ].join('\n')
    assert.deepEqual(lines('a.ts', text), [])
  })

  it('skips a generated file', () => {
    assert.deepEqual(
      lines(
        'a_pb.ts',
        '// @generated by protoc-gen-es\ninterface A {\n  /** x */\n  x: string\n}\n',
      ),
      [],
    )
  })
})

describe('length of a doc comment', () => {
  const doc = (count) => [
    '/**',
    ...Array.from({ length: count }, (_, i) => ` * Line ${i + 1}.`),
    ' */',
  ]

  it('accepts a doc of five lines and rejects one of six, on every exported kind', () => {
    const declarations = [
      'export function f() {}',
      'export class C {}',
      'export interface I {}',
      'export type T = string',
      'export const v = 1',
      'export const g = () => {}',
      'export enum E {}',
    ]
    for (const declaration of declarations) {
      assert.deepEqual(lines('a.ts', [...doc(5), declaration].join('\n')), [], declaration)
      assert.deepEqual(lines('a.ts', [...doc(6), declaration].join('\n')), [1], declaration)
    }
  })

  it('counts a one-line block as one line and a blank line as a line', () => {
    assert.deepEqual(lines('a.ts', '/** One. */\nexport function f() {}'), [])
    const blank = [
      '/**',
      ' * A.',
      ' * B.',
      ' *',
      ' * C.',
      ' * D.',
      ' * E.',
      ' */',
      'export function f() {}',
    ]
    assert.deepEqual(lines('a.ts', blank.join('\n')), [1])
  })

  it('does not limit an unexported symbol, a line comment or a member', () => {
    assert.deepEqual(lines('a.ts', [...doc(6), 'const v = 1'].join('\n')), [])
    const method = ['export class C {', ...doc(6), 'flush() {}', '}']
    assert.deepEqual(lines('a.ts', method.join('\n')), [])
  })

  it('reads the script of a Vue component', () => {
    const text = ['<script lang="ts">', ...doc(6), 'export function f() {}', '</script>'].join('\n')
    assert.deepEqual(lines('A.vue', text), [2])
  })

  it('leaves the long doc in place on --fix', () => {
    const text = [...doc(6), 'export function f() {}'].join('\n')
    const [finding] = findScriptComments('a.ts', text)
    assert.equal(finding.long, true)
  })
})

describe('removeRanges', () => {
  it('removes a whole comment line and a trailing comment', () => {
    const text = 'interface A {\n  /** The id. */\n  id: string\n  size: number // in bytes\n}\n'
    const fixed = removeRanges(text, findScriptComments('a.ts', text))
    assert.equal(fixed, 'interface A {\n  id: string\n  size: number\n}\n')
  })
})
