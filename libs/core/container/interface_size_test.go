// structureConfigName is the golangci-lint configuration of the production-only rules, interfacebloat among them.
const structureConfigName = ".golangci-structure.yml"

// readInterfaceMax returns the interfacebloat maximum of a golangci-lint configuration, and whether the
// configuration enables interfacebloat at all.
func readInterfaceMax(path string) (int, bool, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return 0, false, err
	}
	var config struct {
		Linters struct {
			Enable   []string `yaml:"enable"`
			Settings struct {
				Interfacebloat struct {
					Max *int `yaml:"max"`
				} `yaml:"interfacebloat"`
			} `yaml:"settings"`
		} `yaml:"linters"`
	}
	if err := yaml.Unmarshal(raw, &config); err != nil {
		return 0, false, err
	}
	if !slices.Contains(config.Linters.Enable, "interfacebloat") {
		return 0, false, nil
	}
	if config.Linters.Settings.Interfacebloat.Max == nil {
		return 0, false, fmt.Errorf("%s enables interfacebloat and sets no max", path)
	}
	return *config.Linters.Settings.Interfacebloat.Max, true, nil
}

// findStructureConfig returns the structure configuration nearest to a module, in its directory or the
// closest one above it inside the repository.
func findStructureConfig(dir, root string) (string, error) {
	for current := dir; ; current = filepath.Dir(current) {
		path := filepath.Join(current, structureConfigName)
		if _, err := os.Stat(path); err == nil {
			return path, nil
		} else if !errors.Is(err, fs.ErrNotExist) {
			return "", err
		}
		if current == root || filepath.Dir(current) == current {
			return "", nil
		}
	}
}

// interfaceCount is what one walk over interfaces read.
type interfaceCount struct {
	interfaces int
	composed   int
}

// getBloatedInterfaces returns every named interface of the packages' non-generated files whose full method
// set, embedded interfaces included, has more than limit methods.
func getBloatedInterfaces(pkgs []*packages.Package, limit int) ([]finding, interfaceCount) {
	var found []finding
	var count interfaceCount
	for _, pkg := range pkgs {
		for _, file := range pkg.Syntax {
			if ast.IsGenerated(file) {
				continue
			}
			ast.Inspect(file, func(node ast.Node) bool {
				spec, ok := node.(*ast.TypeSpec)
				if !ok {
					return true
				}
				object, ok := pkg.TypesInfo.Defs[spec.Name].(*types.TypeName)
				if !ok || object.IsAlias() {
					return true
				}
				iface, ok := object.Type().Underlying().(*types.Interface)
				if !ok {
					return true
				}
				count.interfaces++
				if iface.NumEmbeddeds() > 0 {
					count.composed++
				}
				if iface.NumMethods() > limit {
					found = append(found, newFinding(pkg.Fset, spec.Name.Pos(),
						pkg.Types.Name()+"."+object.Name()+" has "+strconv.Itoa(iface.NumMethods())+" methods"))
				}
				return true
			})
		}
	}
	return sortFindings(found), count
}

func checkInterfaceSizeCountsTheWholeMethodSet(t *testing.T, workspace workspacePackages) {
	t.Helper()
	root, err := filepath.Abs(repoRootDir)
	if err != nil {
		t.Fatal(err)
	}
	var total interfaceCount
	covered := 0
	for _, dir := range listWorkspaceModules(t) {
		config, err := findStructureConfig(dir, root)
		if err != nil {
			t.Fatal(err)
		}
		if config == "" {
			continue
		}
		limit, isEnabled, err := readInterfaceMax(config)
		if err != nil {
			t.Fatal(err)
		}
		if !isEnabled {
			continue
		}
		covered++
		found, count := getBloatedInterfaces(listProductionPackages(workspace.listModule(t, dir)), limit)
		total.interfaces += count.interfaces
		total.composed += count.composed
		for _, one := range found {
			t.Errorf("%s: %s, more than the %d %s allows", one.position, one.name, limit, config)
		}
	}

	// A walk that reads no interface built from embedded ones checks nothing the linter does not.
	if covered < 10 || total.interfaces < 100 || total.composed == 0 {
		t.Fatalf("%d modules, %d interfaces and %d composed interfaces read: the rule is checked against nothing",
			covered, total.interfaces, total.composed)
	}
}

// The rule counts the methods an interface takes from embedded interfaces, and reads no test file and no
// generated file.
func TestInterfaceSizeRule_CountsEmbeddedMethods(t *testing.T) {
	dir := writeTreeFixture(t, map[string]string{
		"shapes/shapes.go": `package shapes

type Reader interface {
	Read() string
	Size() int
}

type Writer interface{ Write(string) }

type ReadWriter interface {
	Reader
	Writer
}

type Small interface{ Close() error }

func local() {
	type Inner interface {
		ReadWriter
		Close() error
	}
}
`,
		"shapes/shapes_test.go": `package shapes

type Wide interface {
	ReadWriter
	Flush()
}
`,
		"shapes/generated.go": `// Code generated by a tool. DO NOT EDIT.

package shapes

type Service interface {
	ReadWriter
	Flush()
}
`,
	})
	found, count := getBloatedInterfaces(loadFixture(t, dir), 2)
	want := []string{"shapes.go:10 shapes.ReadWriter has 3 methods", "shapes.go:18 shapes.Inner has 4 methods"}
	if got := formatFindings(found); !slices.Equal(got, want) {
		t.Errorf("the rule rejects %v, want %v", got, want)
	}
	if count.interfaces != 5 || count.composed != 2 {
		t.Errorf("%d interfaces and %d composed read, want 5 and 2", count.interfaces, count.composed)
	}
}

// The maximum is read from the configuration, and a configuration without interfacebloat covers nothing.
func TestInterfaceSizeRule_ReadsTheMaximumFromTheConfig(t *testing.T) {
	dir := t.TempDir()
	enabled := filepath.Join(dir, "enabled.yml")
	disabled := filepath.Join(dir, "disabled.yml")
	if err := os.WriteFile(enabled, []byte("linters:\n  enable: [interfacebloat]\n  settings:\n    interfacebloat:\n      max: 7\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(disabled, []byte("linters:\n  enable: [funlen]\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if limit, isEnabled, err := readInterfaceMax(enabled); err != nil || !isEnabled || limit != 7 {
		t.Errorf("read %d, %v, %v; want 7, true, nil", limit, isEnabled, err)
	}
	if _, isEnabled, err := readInterfaceMax(disabled); err != nil || isEnabled {
		t.Errorf("read %v, %v; want false, nil", isEnabled, err)
	}
	if limit, isEnabled, err := readInterfaceMax(filepath.Join(repoRootDir, structureConfigName)); err != nil || !isEnabled || limit < 1 {
		t.Errorf("the repository configuration reads %d, %v, %v", limit, isEnabled, err)
	}
}
