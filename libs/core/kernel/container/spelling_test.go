// getBritishStems returns the stems of words that American English spells another way, in lower case. They
// are derived from the American spelling: -ize for -ise, -or for -our and -er for -re.
func getBritishStems() []string {
	var stems []string
	for _, american := range []string{
		"normaliz", "quantiz", "recogniz", "initializ", "serializ", "synchroniz",
		"minimiz", "maximiz", "customiz", "authoriz", "sanitiz", "summariz", "prioritiz", "localiz", "utiliz",
	} {
		stems = append(stems, strings.ReplaceAll(american, "z", "s"))
	}
	for _, american := range []string{"neighbor", "color", "behavior"} {
		stems = append(stems, strings.ReplaceAll(american, "or", "our"))
	}
	return append(stems, "cent"+"re")
}

func getBritishStem(name string) string {
	lower := strings.ToLower(name)
	for _, stem := range getBritishStems() {
		if strings.Contains(lower, stem) {
			return stem
		}
	}
	return ""
}

func isGeneratedFile(file *ast.File) bool {
	for _, group := range file.Comments {
		for _, one := range group.List {
			if strings.HasPrefix(one.Text, "// Code generated") && strings.HasSuffix(one.Text, "DO NOT EDIT.") {
				return true
			}
		}
	}
	return false
}

// listBritishIdentifiers returns each identifier of the file that contains a stem of British spelling.
func listBritishIdentifiers(path string, src any) ([]finding, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil || isGeneratedFile(file) {
		return nil, err
	}
	var found []finding
	ast.Inspect(file, func(node ast.Node) bool {
		if one, is := node.(*ast.Ident); is && getBritishStem(one.Name) != "" {
			found = append(found, newFinding(fset, one.Pos(), one.Name))
		}
		return true
	})
	return found, nil
}

// No identifier of the libraries and applications is spelled in British English: -ize, -or and -er. Generated files follow the schema they are generated from, and the plugins are not walked.
func TestNoIdentifierIsSpeltInBritishEnglish(t *testing.T) {
	var found []finding
	read := 0
	for _, root := range []string{"libs", "apps"} {
		err := filepath.WalkDir(filepath.Join(repoRootDir, root), func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() && (entry.Name() == "node_modules" || entry.Name() == "testdata") {
				return filepath.SkipDir
			}
			if entry.IsDir() || !strings.HasSuffix(path, ".go") {
				return nil
			}
			one, err := listBritishIdentifiers(path, nil)
			read++
			found = append(found, one...)
			return err
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	for _, one := range sortFindings(found) {
		t.Errorf("%s: %s is spelled in British English", one.position, one.name)
	}
	if read < 500 {
		t.Fatalf("%d Go files read: the walk is not reading the libraries and applications", read)
	}
}

func TestSpellingRule_ReportsBritishIdentifiersAndLeavesGeneratedFilesAlone(t *testing.T) {
	british := strings.ReplaceAll("Normaliz", "z", "s") + "e"
	variable := strings.ReplaceAll("neighbor", "or", "our") + "Set"
	found, err := listBritishIdentifiers("a.go", "package a\n\nfunc "+british+"() {}\n\nvar "+variable+" int\n\nfunc Normalize() {}\n")
	if err != nil {
		t.Fatal(err)
	}
	if got := formatFindings(found); len(got) != 2 || got[0] != "a.go:3 "+british || got[1] != "a.go:5 "+variable {
		t.Errorf("the rule reports %v, want the two British identifiers", got)
	}
	generated, err := listBritishIdentifiers("b.go", "// Code generated by buf. DO NOT EDIT.\n\npackage b\n\nfunc "+british+"() {}\n")
	if err != nil || len(generated) != 0 {
		t.Errorf("a generated file reports %v, %v, want nothing", generated, err)
	}
}
