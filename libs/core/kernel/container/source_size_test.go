package container

import (
	"bytes"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"testing"
)

// maxFileLines and maxPackageLines bound the production source of one file and of one package directory.
// A file of five hundred lines is what a reader takes in at a sitting and what holds one use case or one
// adapter with its helpers; a package of three thousand lines is a dozen such files. A larger package is
// several concerns under one name, and a larger file is a package waiting to be cut.
const (
	maxFileLines    = 500
	maxPackageLines = 3000
)

func listSourceRoots() []string {
	return []string{"libs/core/kernel", "apps/desktop"}
}

func getSourceLines(path string) (int, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return 0, err
	}
	return bytes.Count(raw, []byte("\n")) + btoi(len(raw) > 0 && raw[len(raw)-1] != 10), nil
}

func btoi(ok bool) int {
	if ok {
		return 1
	}
	return 0
}

func isGeneratedPath(path string) (bool, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.PackageClauseOnly|parser.ParseComments)
	if err != nil {
		return false, err
	}
	for _, group := range file.Comments {
		if group.End() > file.Package {
			break
		}
		for _, one := range group.List {
			if strings.HasPrefix(one.Text, "// Code generated") && strings.Contains(one.Text, "DO NOT EDIT") {
				return true, nil
			}
		}
	}
	return false, nil
}

func getOversizedSources(root string, trees []string, fileMax, packageMax int) (found []string, files, dirs int, err error) {
	for _, tree := range trees {
		perDir := map[string]int{}
		walkErr := filepath.WalkDir(filepath.Join(root, tree), func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() {
				if name := entry.Name(); name == "node_modules" || name == "testdata" || strings.HasPrefix(name, ".") && path != filepath.Join(root, tree) {
					return fs.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			isGenerated, err := isGeneratedPath(path)
			if err != nil || isGenerated {
				return err
			}
			lines, err := getSourceLines(path)
			if err != nil {
				return err
			}
			rel, relErr := filepath.Rel(root, path)
			if relErr != nil {
				return relErr
			}
			files++
			perDir[filepath.Dir(rel)] += lines
			if lines > fileMax {
				found = append(found, filepath.ToSlash(rel)+" has "+strconv.Itoa(lines)+" lines, more than "+strconv.Itoa(fileMax))
			}
			return nil
		})
		if walkErr != nil {
			return nil, 0, 0, walkErr
		}
		for dir, lines := range perDir {
			dirs++
			if limit := packageMax; lines > limit {
				found = append(found, filepath.ToSlash(dir)+" has "+strconv.Itoa(lines)+" lines in all, more than "+strconv.Itoa(limit))
			}
		}
	}
	slices.Sort(found)
	return found, files, dirs, nil
}

func TestNoProductionFileOrPackageIsLarge(t *testing.T) {
	root, err := filepath.Abs(repoRootDir)
	if err != nil {
		t.Fatal(err)
	}
	found, files, dirs, err := getOversizedSources(root, listSourceRoots(), maxFileLines, maxPackageLines)
	if err != nil {
		t.Fatal(err)
	}
	for _, one := range found {
		t.Error(one)
	}

	if files == 0 || dirs == 0 {
		t.Fatalf("%d files in %d directories read: the rule is checked against nothing", files, dirs)
	}
}

// The rule counts every line of a production file, reads no test file and no generated file, and sums a
// directory without its subdirectories.
func TestSourceSizeRule_CountsProductionLinesPerFileAndDirectory(t *testing.T) {
	dir := t.TempDir()
	write := func(name, text string) {
		path := filepath.Join(dir, "tree", filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	lines := func(n int) string { return "package p\n" + strings.Repeat("\n", n-1) }
	write("a/long.go", lines(10))
	write("a/short.go", lines(3))
	write("a/long_test.go", lines(50))
	write("a/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage p\n"+strings.Repeat("\n", 50))
	write("a/sub/other.go", lines(4))
	found, files, dirs, err := getOversizedSources(dir, []string{"tree"}, 8, 12)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"tree/a has 13 lines in all, more than 12", "tree/a/long.go has 10 lines, more than 8"}
	if !slices.Equal(found, want) {
		t.Errorf("the rule rejects %v, want %v", found, want)
	}
	if files != 3 || dirs != 2 {
		t.Errorf("%d files and %d directories read, want 3 and 2", files, dirs)
	}
}
