/**
 * The drawing, taken from the code rather than from memory.
 *
 * One diagram per interface module, each collapsed to the folder a component
 * lives in. Nothing here decides anything: the rules are in
 * .dependency-cruiser.cjs and the graph is what they see.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { config, depcruise, modules, root } from './modules.mjs'

const drawn = ({ name, at, sources, says }) => {
  const mermaid = execFileSync(
    depcruise,
    ['--config', config, '--output-type', 'mermaid', '--collapse', '^src/[^/]+', ...sources],
    { cwd: join(root, at), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  ).trim()
  return `## ${name}\n\n${says}\n\n\`${at}\`\n\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n`
}

const page = [
  '# What the interface modules depend on',
  '',
  'Generated by `make graph`; edit nothing here. Each diagram is one module, collapsed to the folder a component lives in. What holds the direction is `modules/tools/depgraph/.dependency-cruiser.cjs`, and ADR-0023 is what it enforces.',
  '',
  ...modules.map(drawn),
].join('\n')

const out = join(root, 'docs/dependencies.md')
writeFileSync(out, page)
console.log(`wrote ${relative(root, out)}`)
