/** The line being spoken at a moment: the last one that has begun, or the first before any has. */
export function getActiveCueIndex(cues: readonly Cue[], ms: number): number {
  return Math.max(
    0,
    cues.findLastIndex((cue) => cue.from <= ms),
  )
}
