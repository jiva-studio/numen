import { describe, expect, it } from 'vitest'
import { findBddTest, parseBddFile } from './bdd-data.js'

const SPEC = `// Generated from: ../../../features/garden/water-plants.feature
import { test } from "../../../../support/test.ts";

const bddFileData = [ // bdd-data-start
  {"pwTestLine":6,"pickleLine":7,"tags":[],"steps":[{"pwStepLine":7,"gherkinStepLine":8,"keywordType":"Action","textWithKeyword":"When the gardener waters"}]},
  {"pwTestLine":10,"pickleLine":24,"tags":[],"steps":[]},
]; // bdd-data-end`

describe('parseBddFile', () => {
  const file = parseBddFile(SPEC, '/repo/tests/acceptance/desktop')

  it('resolves the feature against the folder of the config', () => {
    expect(file.featurePath).toBe('/repo/features/garden/water-plants.feature')
  })

  it('finds a test by the line of its call in the spec', () => {
    expect(findBddTest(file, 6)?.steps[0]).toMatchObject({ pwStepLine: 7, gherkinStepLine: 8 })
    expect(findBddTest(file, 10)?.pickleLine).toBe(24)
  })

  it('refuses a file bddgen did not write', () => {
    expect(() => parseBddFile('export const a = 1', '/repo')).toThrow(
      'not a spec generated by bddgen',
    )
  })
})
