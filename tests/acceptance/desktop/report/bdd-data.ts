import fs from 'node:fs'
import path from 'node:path'

export type BddStep = {
  readonly pwStepLine: number
  readonly gherkinStepLine: number
  readonly textWithKeyword: string
}

export type BddTest = {
  readonly pwTestLine: number
  readonly pickleLine: number
  readonly steps: readonly BddStep[]
}

export type BddFile = {
  readonly featurePath: string
  readonly tests: readonly BddTest[]
}

const GENERATED_FROM = /^\/\/ Generated from: (.+)$/

export const parseBddFile = (content: string, configDir: string): BddFile => {
  const lines = content.split('\n')
  const uri = GENERATED_FROM.exec(lines[0] ?? '')?.[1]?.trim()
  const start = lines.findIndex((line) => line.endsWith('// bdd-data-start'))
  const end = lines.findIndex((line) => line.endsWith('// bdd-data-end'))
  if (!uri || start < 0 || end < start) {
    throw new Error('not a spec generated by bddgen: no "Generated from" line or no bdd data')
  }
  const tests = lines
    .slice(start + 1, end)
    .map((line) => JSON.parse(line.trim().replace(/,$/, '')) as BddTest)
  return { featurePath: path.resolve(configDir, uri), tests }
}

export const readBddFile = (specPath: string, configDir: string): BddFile =>
  parseBddFile(fs.readFileSync(specPath, 'utf8'), configDir)

export const findBddTest = (file: BddFile, pwTestLine: number): BddTest | undefined =>
  file.tests.find((test) => test.pwTestLine === pwTestLine)
